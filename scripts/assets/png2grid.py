"""Converts a hand-drawn PNG (e.g. made in Pixelorama) into a TypeScript pixel grid module.

    python3 -E scripts/assets/png2grid.py scripts/assets/handdrawn/bench.png client/src/art/handdrawn/bench.ts BENCH

Each distinct colour becomes one character of the palette; fully transparent pixels become '.'. The generated file is
what the game imports (client/src/art/handdrawn/grid.ts paints it), so edit the PNG and run this again.
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"


def convert(png: Path, name: str, rel_png: str) -> str:
    img = Image.open(png).convert("RGBA")
    w, h = img.size
    palette: dict[str, str] = {}
    by_color: dict[tuple[int, int, int], str] = {}
    rows = []
    for y in range(h):
        row = ""
        for x in range(w):
            r, g, b, a = img.getpixel((x, y))
            if a < 128:
                row += "."
                continue
            key = (r, g, b)
            if key not in by_color:
                if len(by_color) >= len(CHARS):
                    raise SystemExit(f"{png}: more than {len(CHARS)} colours")
                by_color[key] = CHARS[len(by_color)]
                palette[by_color[key]] = f"#{r:02x}{g:02x}{b:02x}"
            row += by_color[key]
        rows.append(row)
    pal = ", ".join(f"{k}: '{v}'" for k, v in palette.items())
    body = ",\n".join(f"    '{r}'" for r in rows)
    return (
        f"// Generated by scripts/assets/png2grid.py from {rel_png}. Edit the PNG (Pixelorama), not this file.\n"
        f"import type {{ PixelGrid }} from './grid';\n\n"
        f"export const {name}: PixelGrid = {{\n"
        f"  palette: {{ {pal} }},\n"
        f"  rows: [\n{body},\n  ],\n"
        f"}};\n"
    )


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    src, dst, const = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(convert(src, const, str(src)))
    print(f"wrote {dst}")

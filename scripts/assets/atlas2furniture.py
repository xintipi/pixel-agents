"""Turns the hand-drawn furniture atlases (made in Pixelorama) into the TypeScript data the game reads.

    python3 -E scripts/assets/atlas2furniture.py

Reads scripts/assets/handdrawn/furniture/manifest.json (which cell of which atlas is which sprite layer, plus its
anchor and dynamic regions) and the furniture-N.png atlases next to it; writes client/src/art/handdrawn/furniture-data.ts.
Each cell gets its own small palette (colours with alpha become '#rrggbbaa'), so the atlases can use as many colours as
they like. Edit the PNGs in Pixelorama, keep the cells where the manifest says they are, and run this again.
"""

from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "scripts" / "assets" / "handdrawn" / "furniture"
OUT = ROOT / "client" / "src" / "art" / "handdrawn" / "furniture-data.ts"
# Characters that are safe inside a single-quoted TypeScript string ('.' stays transparent).
CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!#$%&()*+,-/:;<=>?@[]^_{|}~"


def cell_rows(img: Image.Image, x0: int, y0: int, w: int, h: int) -> tuple[dict[str, str], list[str]]:
    by: dict[tuple[int, int, int, int], str] = {}
    pal: dict[str, str] = {}
    rows = []
    for y in range(h):
        row = ""
        for x in range(w):
            r, g, b, a = img.getpixel((x0 + x, y0 + y))
            if a == 0:
                row += "."
                continue
            if (r, g, b, a) not in by:
                if len(by) >= len(CHARS):
                    raise SystemExit(f"cell at {x0},{y0}: more than {len(CHARS)} colours")
                by[(r, g, b, a)] = CHARS[len(by)]
                pal[by[(r, g, b, a)]] = f"#{r:02x}{g:02x}{b:02x}" + ("" if a == 255 else f"{a:02x}")
            row += by[(r, g, b, a)]
        rows.append(row)
    return pal, rows


def ts_sprite(meta: dict, pal: dict[str, str], rows: list[str]) -> str:
    rects = json.dumps(meta["rects"]) if meta.get("rects") else None
    p = ", ".join(f"'{k}': '{v}'" if k in "\\'" else f"{k!r}: '{v}'" for k, v in pal.items()).replace('"', "'")
    body = ",\n".join(f"        '{r}'" for r in rows)
    return (
        f"{{ ax: {meta['ax']}, ay: {meta['ay']}, "
        + (f"rects: {rects}, " if rects else "")
        + f"palette: {{ {p} }}, rows: [\n{body},\n      ] }}"
    )


def main() -> None:
    manifest = json.loads((SRC / "manifest.json").read_text())
    atlases = {a["name"]: Image.open(SRC / f"{a['name']}.png").convert("RGBA") for a in manifest["atlases"]}
    cells = {c["id"]: (a["name"], c) for a in manifest["atlases"] for c in a["cells"]}
    entries = []
    for e in manifest["entries"]:
        parts = []
        for layer in ("base", "front"):
            if layer not in e:
                continue
            name, c = cells[f"{e['key']}#{layer}"]
            pal, rows = cell_rows(atlases[name], c["x"], c["y"], c["w"], c["h"])
            parts.append(f"{layer}: " + ts_sprite(e[layer], pal, rows))
        entries.append(f"  '{e['key']}': {{ " + ", ".join(parts) + " },")
    OUT.write_text(
        "// Generated by scripts/assets/atlas2furniture.py from scripts/assets/handdrawn/furniture/*.png.\n"
        "// Edit the PNGs (Pixelorama), not this file.\n"
        "import type { HandFurnitureData } from './furniture';\n\n"
        "export const FURNITURE_DATA: Readonly<Record<string, HandFurnitureData>> = {\n" + "\n".join(entries) + "\n};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} sprites)")


if __name__ == "__main__":
    main()
